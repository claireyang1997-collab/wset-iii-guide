"""Build established chapters 4–6 from their maintained canonical content.

The earlier restructure/editorial migration scripts are historical migrations;
do not rerun them over the canonical content after this handoff.
"""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'content/viticulture.json').read_text())
text = '/* Generated by scripts/build-viticulture.py; edit content/viticulture.json. */\n'
for name, key in [('bookUnits', 'units'), ('bookLegacy', 'legacy'),
                  ('bookSectionOrigins', 'sectionOrigins')]:
    text += f'const {name}=' + json.dumps(data[key], ensure_ascii=False, indent=1) + ';\n'
(root / 'dist/book-data.js').write_text(text)
print(f"Built chapters 4–6 / {len(data['units'])} reading units.")
