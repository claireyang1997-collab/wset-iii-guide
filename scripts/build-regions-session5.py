"""Generate canonical Session 5 data with source crops and reviewed teaching illustrations."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'content/regions-session5.json').read_text())
assert len({(u['chapter'],u['id']) for u in data['units']})==len(data['units'])
assert len({p['sourceId'] for p in data['pages']})==41
figs={f['id'] for f in data['figures']}
for u in data['units']:
    for s in u['sections']:
        assert set(s.get('figures',[]))<=figs
(root/'dist/regions-session5-data.js').write_text('/* Generated by scripts/build-regions-session5.py. */\nconst regionsSession5='+json.dumps(data,ensure_ascii=False,indent=1)+';\n')
print(f"Built {len(data['chapters'])} chapters, {len(data['units'])} units, {len(figs)} figures.")
