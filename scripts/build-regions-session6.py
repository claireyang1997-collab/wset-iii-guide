"""Build verified Bordeaux/Southwest content and shared process worksheets."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'content/regions-session6.json').read_text())
assert len({(u['chapter'],u['id']) for u in data['units']})==len(data['units'])
assert len({p['sourceId'] for p in data['pages']})==37
figs={f['id'] for f in data['figures']}
flows={f['id'] for f in data['flows']}
for u in data['units']:
    for s in u['sections']:
        assert set(s.get('figures',[]))<=figs
        assert not s.get('flow') or s['flow'] in flows
for f in data['figures']:
    assert (root/'dist'/f['src']).exists(),f['src']
(root/'dist/regions-session6-data.js').write_text('/* Generated by scripts/build-regions-session6.py. */\nconst regionsSession6='+json.dumps(data,ensure_ascii=False,indent=1)+';\n')
print(f"Built {len(data['units'])} units, {len(figs)} subject crops, {len(flows)} process diagrams.")
