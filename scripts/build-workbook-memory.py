"""Build the self-study memory layer without altering original question data."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'content/workbook-memory.json').read_text())
assert len({x['id'] for x in data['items']})==len(data['items'])
for group in data['groups']:
    assert all(any(x['id']==key for x in data['items']) for key in group['items'])
text='/* Generated by scripts/build-workbook-memory.py. */\nconst workbookMemoryData='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'+(root/'scripts/workbook-memory.js').read_text()
(root/'dist/workbook-memory.js').write_text(text)
print('Built',len(data['items']),'memory topics for',len(data['groups']),'workbook sessions.')
